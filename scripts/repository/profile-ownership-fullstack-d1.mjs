export const fullstackD1OwnershipRules = fullstackD1OwnershipGroups.flatMap(
    (group) => [
        ...(group.prefixes ?? []).map((prefix) => ({
            description: `${group.name} prefix ${prefix}`,
            matches: (path) => path.startsWith(prefix),
            owner: group.name,
        })),
        ...(group.paths ?? []).map((ownedPath) => ({
            description: `${group.name} path ${ownedPath}`,
            matches: (path) => path === ownedPath,
            owner: group.name,
        })),
        ...(group.apiRelativePaths ?? []).map((relativePath) => {
            const paths = new Set(
                apiSurfaces.map((surface) => `${surface}/${relativePath}`),
            )
            return {
                description: `${group.name} API path ${relativePath}`,
                matches: (path) => paths.has(path),
                owner: group.name,
            }
        }),
    ],
)

export function getFullstackD1Owner(path) {
    return fullstackD1OwnershipRules.find((rule) => rule.matches(path))?.owner
}
